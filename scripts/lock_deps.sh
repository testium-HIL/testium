#!/bin/bash
# Regenerates src/requirements.txt, the pinned dependency set used by the
# source venvs and every binary build (AppImage, PyInstaller, Flatpak).
#
# src/pyproject.toml is the only hand-maintained dependency list: no upper
# bounds, no per-environment exceptions. This script resolves it for the
# lowest supported Python (requires-python) so the pins install everywhere.
#
# Run it when preparing a release, then run the validation suite before
# committing the result. A broken upstream release is handled by not
# committing the refreshed file, never by an exception in pyproject.toml.

set -e

SCRIPT_DIR=$(realpath "$(dirname "$0")")
SRC_DIR="$SCRIPT_DIR/../src"
OUT="$SRC_DIR/requirements.txt"

PY_MIN=$(python3 -c "import re, tomllib; print(re.search(r'[0-9.]+', tomllib.load(open('$SRC_DIR/pyproject.toml', 'rb'))['project']['requires-python']).group())")

TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

python3 -m venv "$TMP/venv"
PY="$TMP/venv/bin/python"
"$PY" -m pip install --quiet --upgrade pip
"$PY" -m pip wheel --quiet --no-deps --wheel-dir "$TMP/wheel" "$SRC_DIR"
"$PY" -m pip install --quiet --dry-run --ignore-installed --only-binary=:all: \
    --python-version "$PY_MIN" --report "$TMP/report.json" "$TMP"/wheel/*.whl

"$PY" - "$TMP/report.json" "$PY_MIN" > "$OUT" <<'EOF'
import json, sys
report = json.load(open(sys.argv[1]))
print("# Generated by scripts/lock_deps.sh from src/pyproject.toml "
      f"(Python {sys.argv[2]}). Do not edit.")
for item in sorted(report["install"], key=lambda i: i["metadata"]["name"].lower()):
    name, version = item["metadata"]["name"], item["metadata"]["version"]
    if name.lower() != "testium-hil":
        print(f"{name}=={version}")
EOF

echo "$OUT regenerated for Python $PY_MIN"
